// Regenerate src/abi.ts from the Foundry build of ../../standards (run `forge build` there first).
import { readFileSync, writeFileSync } from "node:fs";

const contracts = ["AgentMandateVault", "QuantumEscapeRegistry", "PaidReviews"];
let out = "// Generated by scripts/abi.ts from the standards build. Do not edit by hand.\n\n";
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(`../../standards/out/${name}.sol/${name}.json`, "utf8"));
  const id = name[0].toLowerCase() + name.slice(1) + "Abi";
  out += `export const ${id} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
writeFileSync("src/abi.ts", out);
console.log("wrote src/abi.ts for", contracts.join(", "));
